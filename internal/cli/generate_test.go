func TestRunGenerateOnce(t *testing.T) {
	// Create temp directory
	tmpDir, err := os.MkdirTemp("", "sparktype-test-*")
	if err != nil {
		t.Fatalf("failed to create temp dir: %v", err)
	}
	defer os.RemoveAll(tmpDir)

	// Copy test files to temp dir
	testDataDir, _ := filepath.Abs("testdata")

	// Copy simple.yaml
	specContent, _ := os.ReadFile(filepath.Join(testDataDir, "simple.yaml"))
	os.WriteFile(filepath.Join(tmpDir, "simple.yaml"), specContent, 0644)

	// Use relative output path - this tests that paths are resolved relative to config
	configContent := `{
  "specs": {
    "api": {
      "path": "./simple.yaml"
    }
  },
  "outputs": [
    {
      "path": "./output/types.ts",
      "format": "typescript",
      "contents": ["api:*"]
    }
  ]
}`
	configPath := filepath.Join(tmpDir, "typegen.jsonc")
	os.WriteFile(configPath, []byte(configContent), 0644)

	// Run generation
	err = runGenerateOnce(configPath)
	if err != nil {
		t.Fatalf("runGenerateOnce failed: %v", err)
	}

	// Verify output was created (resolved relative to config directory)
	outputPath := filepath.Join(tmpDir, "output", "types.ts")
	if _, err := os.Stat(outputPath); os.IsNotExist(err) {
		t.Error("output file was not created")
	}
}

func TestContentResolver_Integration(t *testing.T) {
	testDataDir, _ := filepath.Abs("testdata")
	registry := spec.NewRegistry(map[string]config.Spec{
		"api": {Path: filepath.Join(testDataDir, "simple.yaml")},
	}, testDataDir)

	resolver := contents.NewResolver(registry)

	// Test wildcard pattern
	tree, err := resolver.Resolve([]config.ContentItem{
		{Pattern: "api:*"},
	})
	if err != nil {
		t.Fatalf("resolve failed: %v", err)
	}

	if len(tree.Nodes) == 0 {
		t.Error("expected nodes from wildcard pattern")
	}

	// Test specific pattern
	tree, err = resolver.Resolve([]config.ContentItem{
		{Pattern: "api:User"},
	})
	if err != nil {
		t.Fatalf("resolve failed: %v", err)
	}

	if len(tree.Nodes) != 1 {
		t.Errorf("expected 1 node for User, got %d", len(tree.Nodes))
	}
}

func TestGeneratorRegistry_Integration(t *testing.T) {
	// Test that all generators are registered
	formats := []string{"typescript", "zod", "python", "go"}

	for _, format := range formats {
		t.Run(format, func(t *testing.T) {
			gen, err := generators.Get(format)
			if err != nil {
				t.Errorf("generator %q not found: %v", format, err)
				return
			}
			if gen.Name() != format {
				t.Errorf("expected name %q, got %q", format, gen.Name())
			}
		})
	}
}
