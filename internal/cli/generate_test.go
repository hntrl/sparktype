func TestProcessOutput_TypeScript(t *testing.T) {
	// Create temp directory for output
	tmpDir, err := os.MkdirTemp("", "sparktype-test-*")
	if err != nil {
		t.Fatalf("failed to create temp dir: %v", err)
	}
	defer os.RemoveAll(tmpDir)

	// Setup test data
	testDataDir, _ := filepath.Abs("testdata")
	registry := spec.NewRegistry(map[string]config.Spec{
		"api": {Path: filepath.Join(testDataDir, "simple.yaml")},
	}, testDataDir)

	output := config.Output{
		Path:     filepath.Join(tmpDir, "types.ts"),
		Format:   "typescript",
		Contents: []config.ContentItem{{Pattern: "api:*"}},
	}

	err = processOutput(registry, output, config.Options{}, tmpDir)
	if err != nil {
		t.Fatalf("processOutput failed: %v", err)
	}

	// Verify output file exists
	content, err := os.ReadFile(output.Path)
	if err != nil {
		t.Fatalf("failed to read output: %v", err)
	}

	// Check content contains expected elements
	contentStr := string(content)
	expectedStrings := []string{
		"Generated by an automated build step",
		"export interface User",
		"id: number",
		"email: string",
		"export type Status",
	}

	for _, expected := range expectedStrings {
		if !strings.Contains(contentStr, expected) {
			t.Errorf("output missing expected string: %q", expected)
		}
	}
}

